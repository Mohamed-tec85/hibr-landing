function getCurrentLang(){
  try{
    const saved = localStorage.getItem('chattlle-lang');
    if(saved === 'ar' || saved === 'en') return saved;
  }catch(e){}
  const browser = (navigator.language || 'ar').toLowerCase();
  return browser.startsWith('ar') ? 'ar' : 'en';
}

